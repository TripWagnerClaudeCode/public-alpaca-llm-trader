"""Broker-agnostic interface. Alpaca is the first implementation; Robinhood/IBKR can follow."""
from __future__ import annotations

from typing import Protocol

from bot.models import AccountState, OrderPlan, SubmittedOrder


class Broker(Protocol):
    name: str
    is_paper: bool

    def get_account(self) -> AccountState: ...
    def is_market_open(self) -> bool: ...
    def submit(self, order: OrderPlan) -> SubmittedOrder: ...
    def cancel_all(self) -> None: ...
    def order_status(self, broker_order_id: str) -> dict: ...
    def tradable(self, symbols: list[str]) -> dict[str, bool]: ...
    # {symbol: {"tradable": bool, "fractionable": bool}}; unknown symbols are not tradable.
    def assets(self, symbols: list[str]) -> dict[str, dict[str, bool]]: ...
    # {"bid": float, "ask": float, "ts": str} or None when no usable quote.
    def latest_quote(self, symbol: str) -> dict | None: ...
